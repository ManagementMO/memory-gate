// The memory map's land: Natural Earth 110m (world-atlas, public domain) drawn flat (equirectangular), cropped to
// 84°N–58°S so Antarctica doesn't take a third of a phone screen. One SVG path, written into the app as a module,
// so the map never fetches tiles and works offline. Pins use the same frame (src/map/atlas.ts toMap).
//   node apps/gate/scripts/prepare-map.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoEquirectangular, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const topo = require('world-atlas/land-110m.json');

const WIDTH = 1000, NORTH = 84, SOUTH = -58;
const scale = WIDTH / (2 * Math.PI);
const height = Math.round(((NORTH - SOUTH) / 360) * WIDTH * 10) / 10;
const projection = geoEquirectangular().scale(scale).translate([WIDTH / 2, scale * (NORTH * Math.PI / 180)]).clipExtent([[0, 0], [WIDTH, height]]);
const d = geoPath(projection).digits(1)(feature(topo, topo.objects.land));

const out = path.resolve(here, '../src/map/land.ts');
writeFileSync(out, `// Generated by apps/gate/scripts/prepare-map.mjs from Natural Earth 110m land (world-atlas 2.0.2, public domain).
// Do not edit by hand: change the script and run it again.
export const MAP = { width: ${WIDTH}, height: ${height}, north: ${NORTH}, south: ${SOUTH} } as const;
export const LAND = '${d}';
`);
console.log(`land.ts: ${(d.length / 1024).toFixed(0)} KB of path, ${WIDTH}×${height}`);
