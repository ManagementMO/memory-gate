// The San Francisco memory map's land: the city's 41 analysis neighborhoods (their union is the land) and its parks,
// from DataSF (data.sfgov.org, public domain), projected flat (equirectangular at the city's latitude), simplified,
// and written as SVG paths to src/map/sfLand.ts. The Marin headlands' tip, across the Golden Gate, is drawn by hand.
//   node apps/gate/scripts/prepare-sf-map.mjs
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../src/map/sfLand.ts');
const BOX = { west: -122.535, east: -122.355, south: 37.705, north: 37.845 };
const LAT0 = 37.775;
const W = 1000;
const K = W / ((BOX.east - BOX.west) * Math.cos((LAT0 * Math.PI) / 180));
const H = Math.round((BOX.north - BOX.south) * K);
const proj = ([lng, lat]) => [(lng - BOX.west) * Math.cos((LAT0 * Math.PI) / 180) * K, (BOX.north - lat) * K];

// Douglas-Peucker on one ring
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let best = -1, far = tol;
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > far) { far = d; best = i; }
    }
    if (best > 0) { keep[best] = 1; stack.push([a, best], [best, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const ring = (coords, tol) => {
  // a closed ring starts and ends on the same point: simplify its two halves, split at the point farthest from the start
  const all = coords.map(proj);
  let far = 0;
  for (let i = 1; i < all.length; i++) if (Math.hypot(all[i][0] - all[0][0], all[i][1] - all[0][1]) > Math.hypot(all[far][0] - all[0][0], all[far][1] - all[0][1])) far = i;
  const pts = far > 0 ? [...simplify(all.slice(0, far + 1), tol), ...simplify(all.slice(far), tol).slice(1)] : all;
  return pts.length < 3 ? '' : `M${pts.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join('L')}Z`;
};
async function shapes(url, tol, min = 0) {
  const g = await (await fetch(url)).json();
  const paths = [];
  for (const f of g.features) {
    const polys = f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates];
    for (const poly of polys) {
      const d = poly.map((r) => ring(r, tol)).filter(Boolean).join('');
      if (d && d.length > min) paths.push(d);
    }
  }
  return paths;
}

const land = await shapes('https://data.sfgov.org/resource/j2bu-swwd.geojson?$limit=100', 0.7);
const parks = await shapes('https://data.sfgov.org/resource/gtr9-ntp6.geojson?$limit=500', 0.9, 60);
const marin = ring([[-122.535, 37.845], [-122.535, 37.8235], [-122.522, 37.8225], [-122.511, 37.8262], [-122.4985, 37.8250], [-122.488, 37.8285], [-122.4785, 37.8275], [-122.4745, 37.8322], [-122.4705, 37.8378], [-122.4672, 37.845]], 0.3);
const bridge = [proj([-122.4785, 37.8275]), proj([-122.4772, 37.8106])].map(([x, y]) => [+x.toFixed(1), +y.toFixed(1)]);

writeFileSync(out, `// Generated by apps/gate/scripts/prepare-sf-map.mjs from DataSF's neighborhoods and parks (public domain).
// Do not edit by hand: change the script and run it again.
export const SF_VIEW = { w: ${W}, h: ${H} };
export const SF_BOX = ${JSON.stringify(BOX)};
export const SF_K = ${K.toFixed(3)};
export const SF_LAT0 = ${LAT0};
export const SF_LAND: string[] = ${JSON.stringify([...land, marin])};
export const SF_PARKS: string[] = ${JSON.stringify(parks)};
export const SF_BRIDGE: [[number, number], [number, number]] = ${JSON.stringify(bridge)};
`);
console.log(`${land.length} land shapes, ${parks.length} parks → ${path.relative(process.cwd(), out)} (${W}×${H})`);
