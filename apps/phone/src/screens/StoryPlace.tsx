import { useEffect, useState } from 'react';
import { useMutation } from 'convex/react';
import type { FunctionReturnType } from 'convex/server';
import { api } from '../../../../convex/_generated/api';
import { fileUrl } from '../backend';
import { useRunner } from '../hooks';
import { Chip, useToast } from '../ui';
import type { Session } from '../session';

type RoomView = FunctionReturnType<typeof api.rooms.get>;
type Words = FunctionReturnType<typeof api.utterances.recent>[number];

/** Family-led preparation; recording a story never starts a paid world generation automatically. */
export function StoryPlace({ session, view, latest, onConsent }: {
  session: Session; view: RoomView; latest?: Words; onConsent: () => void;
}) {
  const make = useMutation(api.splats.fromStory), activate = useMutation(api.splats.setActive), open = useMutation(api.rooms.open);
  const practice = useMutation(api.splats.usePracticeWorld);
  const toast = useToast(), { busy, run } = useRunner(toast.report);
  const [approved, setApproved] = useState(false);
  useEffect(() => setApproved(false), [latest?.id]);
  const scopes = new Set(view.consents.flatMap(c => c.scopes));
  const permitted = scopes.has('voice_processing') && scopes.has('vendor_upload_worldlabs');
  const places = view.recentSplats.filter(s => s.sourceStory);
  const existing = places.find(s => s.sourceStory?.id === latest?.id);
  const generating = view.recentSplats.some(s => ['queued', 'running'].includes(s.status));
  const eligible = latest?.status === 'done' && latest.transcript.length >= 24;
  const auth = { code: session.code, token: session.token };
  return <section className="card story-place" data-testid="story-place" aria-labelledby="story-place-h">
    <p className="eyebrow">Their words. A place to share.</p>
    <h3 id="story-place-h">Let the place take shape.</h3>
    <p>A realistic setting can be imagined from a story. Prepare it together, then add the details as the storyteller speaks.</p>
    {view.room.demo && view.preparedCourtyardAvailable && !view.splat?.sourceStory && <div className="place-result">
      <p><strong>Try the prepared courtyard.</strong> A photoreal World Labs setting, imagined from fictional sample words. Your objects and story stay in place.</p>
      <button className="btn btn-primary" type="button" data-testid="practice-world-open" disabled={!!busy || view.room.paused}
        onClick={() => run('practice', () => practice(auth))}>Open the prepared World Labs courtyard</button>
      <p className="muted small">Already generated and cached. Opening it uses no generation credits.</p>
    </div>}
    {places.map(place => <article className={`place-result is-${place.status}`} key={place.id} data-testid="story-place-result" data-status={place.status}>
      <div className="row wrap"><Chip kind={place.status === 'ready' ? 'confirmed' : 'imagining'}>
        {place.status === 'ready' ? view.splat?.id === place.id ? 'Sharing this place' : 'Ready to review' : place.status === 'failed' ? 'The place could not be made' : 'Imagining the place…'}
      </Chip><span className="muted small">World Labs · AI scenery</span></div>
      <ol className="place-steps" aria-label="Place preparation">
        <li className="done">Words saved</li><li className={place.status === 'ready' ? 'done' : 'current'}>Place imagined</li><li className={view.splat?.id === place.id ? 'done' : ''}>Open together</li>
      </ol>
      {place.previewUrl && <img className="place-preview" src={fileUrl(place.previewUrl) ?? ''} alt="Preview of the imagined setting generated by World Labs" loading="lazy" />}
      <blockquote className="quote">“{place.sourceStory?.transcript}”</blockquote>
      <p className="muted small">{place.sourceStory?.speaker} · {place.sourceStory?.source === 'fixture' ? 'fictional demo source' : place.sourceStory?.source === 'typed' ? 'typed source' : 'spoken source'}. The generated details are an interpretation.</p>
      {place.status === 'ready' ? <button type="button" className="btn btn-primary" data-testid="story-place-open" disabled={!!busy || view.room.paused}
        onClick={() => run('open', async () => { await activate({ ...auth, splatId: place.id }); await open(auth); toast.say('Opening this place together.', 'ok'); })}>
        {view.splat?.id === place.id ? 'Reveal this place again' : 'Open this place together'}
      </button> : <p className="muted small" role="status">{place.status === 'failed' ? 'Your story is safe and the current place is still available. Check Room settings to recover an existing operation; retrying here will not submit another paid request.' : 'This takes several minutes. Keep telling the story; the current setting stays available. The new place will wait here for your review.'}</p>}
    </article>)}
    {!existing && <details className="place-request" data-testid="story-place-request">
      <summary>Imagine a setting from the latest words</summary>
      {latest ? <><blockquote className="quote">“{latest.transcript}”</blockquote><p className="muted small">Source: {latest.speaker}</p></> : <p>Record or type a description of a place first.</p>}
      <p className="muted small">World Labs receives these words to create private AI scenery. It takes several minutes and normally uses 1,580 API credits. Objects mentioned in the story remain separate so you can review and move them. This does not reconstruct or verify a memory.</p>
      {!permitted ? <button className="btn" type="button" onClick={onConsent}>Choose story and World Labs permissions</button> : <>
        <label className="place-approval"><input type="checkbox" checked={approved} onChange={e => setApproved(e.target.checked)} data-testid="story-place-approve" /> Use these words to imagine a setting</label>
        <button className="btn btn-primary" type="button" data-testid="story-place-generate" disabled={!approved || !eligible || !view.flags['worldlabs.generate'] || generating || !!busy || view.room.paused}
          onClick={() => latest && run('generate', async () => { await make({ ...auth, utteranceId: latest.id }); setApproved(false); })}>
          {busy === 'generate' ? 'Saving the request…' : 'Generate a place · 1,580 credits'}
        </button>
        {!view.flags['worldlabs.generate'] && <p className="muted small">New world generation is unavailable. Saved places still open.</p>}
      </>}
    </details>}
  </section>;
}
